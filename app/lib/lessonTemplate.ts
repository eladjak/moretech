// Tier-0 deterministic lesson-plan generator — ALWAYS works, no API key required.
// Produces a full, pedagogically-structured Hebrew lesson plan from the inputs.
// Upgraded to real AI (Tier-1) when an API key is present (see /api/generate-lesson).

export type LessonInput = {
  subject: string;
  gradeLevel: string;
  topic: string;
  duration?: string;
  notes?: string;
};

function pickOpeners(topic: string): string {
  return `פתיחה (5–10 דקות) — הנעה ורלוונטיות
• פותחים בשאלה מסקרנת: "מה אתם כבר יודעים על ${topic}? איפה פגשתם את זה בחיים?"
• מציגים דוגמה קצרה מהיומיום של התלמידים שמחברת אותם לנושא.
• כותבים על הלוח את שאלת השיעור המרכזית, ומבקשים השערה ראשונית.`;
}

function pickBody(topic: string, subject: string): string {
  return `גוף השיעור (25–35 דקות) — בנייה והתנסות
• הסבר ממוקד: מציגים את מושגי המפתח של ${topic} בשפה ברורה, עם דוגמה מ${subject}.
• פעילות מרכזית: התלמידים עובדים בזוגות / קבוצות קטנות על משימה יישומית סביב ${topic}.
• סבב שיתוף קצר: כל קבוצה מציגה תובנה אחת, והמורה מחבר לרעיון הגדול.
• המחשה / תרגול: דוגמה נוספת או תרגיל שמעמיק את ההבנה ומאתגר את התלמידים.`;
}

function pickClose(topic: string): string {
  return `סיכום (5–10 דקות) — רפלקציה והפנמה
• חוזרים לשאלת השיעור ובודקים: מה למדנו על ${topic}?
• כל תלמיד משלים בכרטיסיית יציאה: "דבר אחד חדש שלמדתי" + "שאלה אחת שנשארה לי".
• מקשרים לשיעור הבא ולמטרת ההמשך.`;
}

export function buildLessonPlan(input: LessonInput): string {
  const { subject, gradeLevel, topic } = input;
  const duration = input.duration?.trim() || "45 דקות";
  const notes = input.notes?.trim();

  return `# מערך שיעור: ${topic}

**מקצוע:** ${subject}
**שכבת גיל:** ${gradeLevel}
**משך השיעור:** ${duration}

## מטרות השיעור
בסיום השיעור התלמידים יוכלו:
1. **ידע** — להסביר את מושגי היסוד של ${topic} ולתת דוגמה משלהם.
2. **מיומנות** — ליישם את הנלמד במשימה מעשית ב${subject}.
3. **ערך** — לפתח עמדה אישית ושיקול דעת ביחס ל${topic}.

## ידע קודם נדרש
• היכרות בסיסית עם מושגי היסוד של ${subject} ברמת ${gradeLevel}.
• יכולת לעבוד בזוגות / קבוצות קטנות.

## חומרים ואמצעים
• מצגת / לוח עם שאלת השיעור.
• דף משימה לפעילות המרכזית (זוגות / קבוצות).
• כרטיסיות יציאה לסיכום.

## מהלך השיעור

### ${pickOpeners(topic)}

### ${pickBody(topic, subject)}

### ${pickClose(topic)}

## דיפרנציאציה
• **מתקשים:** משימה מובנית עם דוגמה פתורה ושלבים ברורים; עבודה בזוג עם עמית מנחה.
• **מתקדמים:** אתגר הרחבה — שאלה פתוחה או חיבור ${topic} לתחום נוסף.
• **חינוך מיוחד:** צמצום כמות הטקסט, שימוש בייצוג ויזואלי, וזמן עיבוד נוסף.

## הערכה מעצבת
• תצפית על העבודה בקבוצות ושאלות מכוונות במהלך הפעילות.
• ניתוח כרטיסיות היציאה כדי לזהות פערים לקראת השיעור הבא.

## הרחבה ושיעורי בית
• משימה קצרה ליישום ${topic} בבית או חיבור לדוגמה אישית.
• הצעה לפרויקט המשך לתלמידים שמתחברים לנושא.

## הערות למורה
• השאירו מקום לסקרנות — שאלה טובה של תלמיד שווה יותר מתשובה מוכנה.
• אם הפעילות המרכזית "תופסת", אפשר לקצר את ההסבר ולתת לה יותר זמן.${
    notes ? `\n• בהתאם לבקשתכם: ${notes}` : ""
  }

---
_מערך זה נוצר באמצעות מחולל השיעורים של EduTech (גרסת תבנית). חיבור מפתח AI מפיק מערך מותאם-עומק ייחודי לכל קלט._`;
}
